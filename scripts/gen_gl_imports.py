#!/usr/bin/env python3
"""Generate native/GlImports.cpp: the module's OpenGL ES imports.

Each `env.glXxx` import of generated/th20.h forwards to the native GLES call.
Pointer parameters (per the GLES 3.0 prototype) are module addresses and are
resolved against the memory base; a few calls are special:
  glVertexAttribPointer / glDrawElements: the pointer is a buffer offset
  glShaderSource: an array of module addresses
  glBindFramebuffer / glBlitFramebuffer: the window blit is letterboxed
  glBufferData / glBufferSubData: appends to an orphaned buffer skip the sync
Usage: gen_gl_imports.py generated/th20.h /usr/include/GLES3/gl3.h out.cpp
"""
import re, sys
header, gl3, out = sys.argv[1:4]
imports = {}
for m in re.finditer(r'^(\w+) w2c_env_(gl\w+)\(struct w2c_env\*(?:, )?([^)]*)\);', open(header).read(), re.M):
    ret, name, args = m.groups()
    imports[name] = (ret, [a.strip() for a in args.split(',') if a.strip()])
protos = {}
for m in re.finditer(r'GL_APICALL\s+(.+?)\s*GL_APIENTRY\s+(gl\w+)\s*\(([^)]*)\);', open(gl3).read(), re.S):
    ret, name, params = m.groups()
    ps = [' '.join(p.split()) for p in params.split(',')] if params.strip() != 'void' else []
    protos[name] = (ret.strip(), ps)
special = {'glVertexAttribPointer', 'glDrawElements', 'glShaderSource', 'glBindFramebuffer', 'glBlitFramebuffer',
           'glBufferData', 'glBufferSubData'}
lines = ['// Generated by scripts/gen_gl_imports.py - do not edit.',
         '// OpenGL ES 3.0 imports of the TH20 module, forwarded to the native driver.',
         '#include "GlImports.hpp"', 'namespace th20n::perf { Totals totals; }', 'extern "C" {']
for name in sorted(imports):
    ret, args = imports[name]
    if name not in protos: sys.exit('no GLES prototype for ' + name)
    pret, params = protos[name]
    if len(params) != len(args): sys.exit('arity mismatch ' + name)
    sig = ', '.join(f'{t} a{i}' for i, t in enumerate(args))
    head = f'{ret} w2c_env_{name}(struct w2c_env*' + (', ' + sig if sig else '') + ')'
    if name in special:
        call_args = ', '.join(f'a{i}' for i in range(len(args)))
        body = f'{"return " if ret != "void" else ""}th20n::gl::{name}({call_args});'
    else:
        conv = []
        for i, (p, t) in enumerate(zip(params, args)):
            if '*' in p:
                ctype = p.rsplit(' ', 1)[0] if not p.endswith('*') else p
                ctype = re.sub(r'\b\w+$', '', p).strip() if not p.endswith('*') else p
                conv.append(f'reinterpret_cast<{ctype}>(th20n::ptr(a{i}))')
            elif p.startswith('GLfloat') or p.startswith('GLclampf'):
                conv.append(f'a{i}')
            else:
                ptype = p.rsplit(' ', 1)[0]
                conv.append(f'static_cast<{ptype}>(a{i})')
        call = f'{name}({", ".join(conv)})'
        if ret == 'void': body = call + ';'
        else: body = f'return static_cast<{ret}>({call});'
    extra = ''
    draw_counts = {'glDrawArrays': ('a2', '1'), 'glDrawElements': ('a1', '1'), 'glDrawArraysInstanced': ('a2', 'a3'),
                   'glDrawElementsInstanced': ('a1', 'a4'), 'glDrawRangeElements': ('a3', '1')}
    if name in draw_counts:
        extra = ' ++th20n::perf::totals.draws;'
        # GlOptimize.cpp: work the GPU can skip; the desktop profiler (GlProfile.cpp): pixels written.
        body = ('const auto fix = th20n::glstate::before_draw(); th20n::glprof::draw_begin(); ' + body +
                f' th20n::glprof::draw_end({draw_counts[name][0]}, {draw_counts[name][1]}); th20n::glstate::after_draw(fix);')
    elif name == 'glClear':
        body = 'th20n::glprof::clear(a0); ' + body
    # State GlOptimize.cpp keeps track of (after the call).
    track = {'glEnable': 'th20n::glstate::enable(a0, true);', 'glDisable': 'th20n::glstate::enable(a0, false);',
             'glBlendFunc': 'th20n::glstate::blend_func(a0, a1, a0, a1);', 'glBlendFuncSeparate': 'th20n::glstate::blend_func(a0, a1, a2, a3);',
             'glBlendEquation': 'th20n::glstate::blend_equation(a0, a0);', 'glBlendEquationSeparate': 'th20n::glstate::blend_equation(a0, a1);',
             'glColorMask': 'th20n::glstate::color_mask(a0 != 0, a1 != 0, a2 != 0, a3 != 0);',
             'glDepthFunc': 'th20n::glstate::depth_func(a0);', 'glDepthMask': 'th20n::glstate::depth_mask(a0 != 0);'}
    if name in track:
        if ret != 'void': sys.exit('tracked call with a result: ' + name)
        body = body + ' ' + track[name]
    elif name == 'glBufferData':
        extra = ' if (a2) th20n::perf::totals.upload_bytes += a1;'   # a null pointer only orphans the buffer
    elif name == 'glBufferSubData':
        extra = ' th20n::perf::totals.upload_bytes += a2;'
    elif name in ('glTexImage2D', 'glTexSubImage2D'):
        extra = ' th20n::perf::totals.upload_bytes += std::uint64_t(a3) * a4 * 4;' if name == 'glTexImage2D' else ' th20n::perf::totals.upload_bytes += std::uint64_t(a4) * a5 * 4;'
    lines.append(f'{head} {{ th20n::perf::GlScope scope;{extra} {body} }}')
lines.append('}')
open(out, 'w').write('\n'.join(lines) + '\n')
print(f'{len(imports)} GL imports')
